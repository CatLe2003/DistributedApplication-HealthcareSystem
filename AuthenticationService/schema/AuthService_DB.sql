-- ===========================================
-- 0) DATABASE
-- ===========================================
DROP DATABASE IF EXISTS auth_service_db;
CREATE DATABASE auth_service_db;
\c auth_service_db

-- ===========================================
-- 1) TABLE (userid INT identity; login_key TEXT; reference_id BIGINT)
-- ===========================================
CREATE TABLE IF NOT EXISTS users (
  userid        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN','DOCTOR','STAFF','PATIENT')),
  login_key     TEXT NOT NULL UNIQUE,   -- ADMIN/EMPLOYEE = mã (ADMIN-00001/DR-xxxx/EMP-xxxxx); PATIENT = phone (+84...)
  reference_id  INT,                 -- FK số nguyên: DOCTOR/STAFF -> employees PK (EmployeeService); PATIENT -> patients PK (PatientService)
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


